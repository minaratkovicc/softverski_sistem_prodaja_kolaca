    void refreshTable() {
        TableModelRacuni tm = (TableModelRacuni) tblRacuni.getModel();
        tm.refreshTable();
    }

    private void popuniKupce() {
        try {
        cmbKupac.removeAllItems();
        cmbKupac.addItem("Svi kupci");
        for (Kupac k : controller.ClientController.getInstance().getAllKupac()) {
            cmbKupac.addItem(k);
        }
    } catch (Exception ex) {
        JOptionPane.showMessageDialog(this, "Greška pri učitavanju kupaca.");
    }
       
    }

    private void popuniPoslasticare() {
    try {
        cmbPoslasticar.removeAllItems();
        cmbPoslasticar.addItem("Svi poslastičari");
        for (Poslasticar p : controller.ClientController.getInstance().getAllPoslasticar()) {
            cmbPoslasticar.addItem(p);
        }
    } catch (Exception ex) {
        JOptionPane.showMessageDialog(this, "Greška pri učitavanju poslastičara.");
    }
    }
