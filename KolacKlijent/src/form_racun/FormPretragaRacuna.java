    private void btnDetaljiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDetaljiActionPerformed

        int row = tblRacuni.getSelectedRow();

        if (row >= 0) {
            Racun r = ((TableModelRacuni) tblRacuni.getModel()).getSelectedRacun(row);
            JOptionPane.showMessageDialog(this, "Sistem je našao račun.");
            new FormDetaljiRacuna(this, true, r).setVisible(true);
        }else{
        JOptionPane.showMessageDialog(this,"Sistem ne moze da nadje racun.","Greška",JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnDetaljiActionPerformed

    private void btnPretraziActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPretraziActionPerformed
        // TODO add your handling code here:
    String param = txtPretraga.getText().trim();
    Object selKupac = cmbKupac.getSelectedItem();
    Kupac kupac = (selKupac instanceof Kupac) ? (Kupac) selKupac : null;

    Object selPoslasticar = cmbPoslasticar.getSelectedItem();
    Poslasticar poslasticar = (selPoslasticar instanceof Poslasticar) ? (Poslasticar) selPoslasticar : null;

    try {
       
        Racun r = new Racun();
        r.setKupac(kupac);
        r.setPoslasticar(poslasticar);
        r.setParametar(param);

        
        ArrayList<Racun> filtriraniRacuni = ClientController.getInstance().getAllRacun(r);

       
        tblRacuni.setModel(new TableModelRacuni(filtriraniRacuni));

        if (filtriraniRacuni.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Sistem ne može da nađe račun po zadatim kriterijumima.",
                    "Greška",
                    JOptionPane.ERROR_MESSAGE);
        } else {
            JOptionPane.showMessageDialog(this,
                    "Sistem je našao račun po zadatim kriterijumima.");
        }

    } catch (Exception ex) {
        JOptionPane.showMessageDialog(this,
                "Sistem ne može da nađe račun po zadatim kriterijumima.",
                "Greška",
                JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnPretraziActionPerformed

