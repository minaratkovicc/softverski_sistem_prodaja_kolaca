    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
        try {

            if (txtUsername.getText().isEmpty()
                    || new String(txtPassword.getPassword()).isEmpty()) {
                JOptionPane.showMessageDialog(this, "Korisnicko ime i lozinka moraju "
                        + "biti popunjeni!");
                return;
            }

            Poslasticar p = new Poslasticar();
            p.setKorisnickoIme(txtUsername.getText());
            p.setLozinka(new String(txtPassword.getPassword()));

            Poslasticar poslasticar = ClientController.getInstance().login(p);
            Sesija.getInstance().setUlogovani(poslasticar);
            JOptionPane.showMessageDialog(this, "Korisničko ime i šifra su ispravni");
            new MainForm().setVisible(true);
            this.dispose();

        } catch (RuntimeException ex) {
            JOptionPane.showMessageDialog(this, "Server nije pokrenut!");
            System.exit(0);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage());
        }

    }//GEN-LAST:event_btnLoginActionPerformed

