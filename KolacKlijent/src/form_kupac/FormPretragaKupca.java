    void refreshTable() {
        TableModelKupci tm = (TableModelKupci) tblKupci.getModel();
        tm.refreshTable();
    }

    private void popuniMesta() {
        try {
            cmbMesto.removeAllItems();
            cmbMesto.addItem("Sva mesta");

            for (Mesto m : ClientController.getInstance().getAllMesto()) {
                cmbMesto.addItem(m);
            }
        } catch (Exception ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Greška pri učitavanju mesta.");
        }
    }

