    private void btnDetaljiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDetaljiActionPerformed

        int row = tblKupci.getSelectedRow();

        if (row >= 0) {
            Kupac k = ((TableModelKupci) tblKupci.getModel()).getSelectedKupac(row);
            JOptionPane.showMessageDialog(this, "Sistem je našao kupca.");
            new FormDetaljiKupca(this, true, k).setVisible(true);
        } else {
            JOptionPane.showMessageDialog(this, "Sistem ne moze da nadje kupca.", "Greška", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnDetaljiActionPerformed

    private void btnPretragaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPretragaActionPerformed
        // TODO add your handling code here:
    String imePrezime = txtPretraga.getText().trim();
    String email = txtEmail.getText().trim();
    Object selected = cmbMesto.getSelectedItem();

    Mesto mesto = null;
    if (selected instanceof Mesto) {
        mesto = (Mesto) selected;
    }

    try {
      
        Kupac k = new Kupac();
        k.setIme(imePrezime);
        k.setEmail(email);
        k.setMesto(mesto);

      
        ArrayList<Kupac> filtriraniKupci = ClientController.getInstance().getAllKupac(k);

       
        tblKupci.setModel(new TableModelKupci(filtriraniKupci));

        
        if (filtriraniKupci.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Sistem ne može da nađe kupce po zadatim kriterijumima.",
                    "Greška",
                    JOptionPane.ERROR_MESSAGE);
        } else {
            JOptionPane.showMessageDialog(this,
                    "Sistem je našao kupce po zadatim kriterijumima.");
        }

    } catch (Exception ex) {
        JOptionPane.showMessageDialog(this,
                "Greška prilikom pretrage: " + ex.getMessage(),
                "Greška",
                JOptionPane.ERROR_MESSAGE);
    }

    }//GEN-LAST:event_btnPretragaActionPerformed

